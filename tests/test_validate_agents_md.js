check('reporting: every check emits exactly one verdict prefix ([PASS] or [FAIL])', () => {
  // For AC-T8-006 the validator emits one line per listed path. The four
  // structural checks (DM-2.1..2.4) and AC-T8-004 each emit exactly one line.
  const dir = makeProjectDir('shape', goodAgentsMd());
  materializeGoodArtifacts(dir);
  const r = runValidator([path.join(dir, 'AGENTS.md')]);
  assert.strictEqual(r.status, 0);
  // Count verdict lines exactly.
  const passLines = (r.stdout.match(/\[PASS\]/g) || []).length;
  // 4 structural (DM-2.1/2.2/2.3/2.4) + AC-T8-004 + 3 AC-T8-006 (one per listed path) = 8.
  assert.strictEqual(passLines, 8,
    `expected 8 [PASS] lines for the 3-path fixture, got ${passLines}\n${r.stdout}`);
  // No [FAIL] lines should be emitted.
  assert.ok(!/\[FAIL\]/.test(r.stdout) && !/\[FAIL\]/.test(r.stderr));
  fs.rmSync(dir, { recursive: true, force: true });
});

check('reporting: failures go to stderr, passes go to stdout', () => {
  // Verify the convention stated in the script header: PASS → stdout,
  // FAIL → stderr. This lets CI capture them separately.
  const dir = makeProjectDir('shape-fail',
    `${GOOD_HEADER}\n\n## Stack\n\n## Local Configuration Files\n\n- \`missing.txt\` — desc\n`);
  const r = runValidator([path.join(dir, 'AGENTS.md')]);
  assert.strictEqual(r.status, 1);
  // All [FAIL] content must be on stderr.
  assert.ok(/\[FAIL\]/.test(r.stderr), '[FAIL] should be on stderr');
  assert.ok(!/\[FAIL\]/.test(r.stdout), '[FAIL] must not leak to stdout');
  // Summary should still be on stdout (informational final line).
  assert.ok(/Summary:/.test(r.stdout), 'summary should be on stdout');
  fs.rmSync(dir, { recursive: true, force: true });
});

