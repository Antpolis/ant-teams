#!/usr/bin/env node
'use strict';

/*
 * tests/test_validate_agents_md.js — SPEC-001-T8 unit tests.
 *
 * Drives `scripts/validate-agents-md.sh` against crafted AGENTS.md inputs
 * and asserts the DM-2 / AC-T8 contract from issue #9 + ARCH-003 + SPEC-001
 * TEST-4:
 *
 *   - AC-T8-001: known-good AGENTS.md exits 0 with all checks passing.
 *   - AC-T8-002: missing generation timestamp on line 1 → [FAIL] + exit 1.
 *   - AC-T8-003: empty H2 section → [FAIL] + exit 1.
 *   - AC-T8-004: placeholder text → [FAIL] + exit 1.
 *   - AC-T8-005: missing '## Local Configuration Files' → [FAIL] + exit 1.
 *   - AC-T8-006: path listed in LCF that does not exist → [FAIL] + exit 1;
 *                directory entries (trailing /) are accepted as well as files.
 *   - DM-2.2:    H1 and H3+ headings → [FAIL] + exit 1.
 *   - DM-2.2/DM-2.3 "valid hand-edits" guardrail: reordered sections and
 *                operator-tweaked generation comment do NOT trigger failures.
 *   - Usage:     missing arg / --help / nonexistent file → exit 2.
 *
 * The validator is a pure bash script (no Node dependency in the script
 * itself). The test harness uses Node only for assertion machinery, matching
 * the pattern in tests/test_skills_copy.js and tests/test_agents_md_gen.js.
 *
 * No external npm dependencies — Node built-ins only.
 */

const { execFileSync } = require('child_process');
const fs = require('fs');
const os = require('os');
const path = require('path');
const assert = require('assert');

const REPO_ROOT = path.resolve(__dirname, '..');
const VALIDATOR = path.join(REPO_ROOT, 'scripts', 'validate-agents-md.sh');

let pass = 0;
let fail = 0;
const failures = [];

function check(name, fn) {
  try {
    fn();
    pass++;
  } catch (err) {
    fail++;
    failures.push({ name, message: err.message, stack: err.stack });
    process.stdout.write(`  FAIL: ${name}\n    ${err.message}\n`);
  }
}

// Run the validator with given argv. Returns {stdout, stderr, status}.
function runValidator(argv) {
  const result = { stdout: '', stderr: '', status: 0 };
  try {
    result.stdout = execFileSync('bash', [VALIDATOR, ...argv], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
      // The validator's repo-root resolution uses `cd` into the parent dir
      // of the AGENTS.md argument, so working directory does not matter.
      cwd: REPO_ROOT,
      timeout: 15000,
    });
  } catch (err) {
    result.status = err.status ?? 1;
    result.stdout = err.stdout ? err.stdout.toString('utf8') : '';
    result.stderr = err.stderr ? err.stderr.toString('utf8') : '';
  }
  return result;
}

// Write `content` to a fresh AGENTS.md inside a temp repo-rooted directory
// and return that directory's path. The validator resolves repo-root as the
// parent dir of the AGENTS.md argument, so files placed in this directory
// are visible to the AC-T8-006 existence check.
function makeProjectDir(prefix, content) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), `validate-amd-${prefix}-`));
  fs.writeFileSync(path.join(dir, 'AGENTS.md'), content);
  return dir;
}

// Canonical known-good generation comment. Mirrors the format the
// init-project generator emits per DM-2.1 / AC-SPEC-012.
const GOOD_HEADER =
  '<!-- Generated by init-project v0.3.0 on 2026-07-21T05:29:36.616Z — edit freely -->';

// Canonical known-good AGENTS.md. Includes all sections the generator is
// allowed to emit (DM-2.2 standard set), has non-empty bodies (DM-2.3),
// has the LCF section (DM-2.4), lists only files that the test setup will
// create on disk (AC-T8-006), and contains no placeholder text (AC-T8-004).
function goodAgentsMd(extra) {
  const lines = [
    GOOD_HEADER,
    '',
    '## Repository Identity',
    '',
    'Demo project',
    'Role: service',
    '',
    '## Stack',
    '',
    'Language: Node.js',
    '',
    '## Local Configuration Files',
    '',
    '- `AGENTS.md` — canonical agent guidance for this repository',
    '- `.github-project.json` — GitHub workflow metadata',
    '- `.opencode/skills/project-initialization/` — re-initialization scripts',
  ];
  if (extra) lines.push(...extra);
  return lines.join('\n') + '\n';
}

// Files the known-good fixture claims exist (AC-T8-006 happy path).
function materializeGoodArtifacts(dir) {
  fs.writeFileSync(path.join(dir, '.github-project.json'), '{}\n');
  fs.mkdirSync(path.join(dir, '.opencode', 'skills', 'project-initialization'), {
    recursive: true,
  });
}

