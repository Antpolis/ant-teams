process.stdout.write('Suite: AC-T8-001 known-good passes\n');

check('AC-T8-001: known-good AGENTS.md exits 0 with all checks passing', () => {
  const dir = makeProjectDir('ac001', goodAgentsMd());
  materializeGoodArtifacts(dir);
  const r = runValidator([path.join(dir, 'AGENTS.md')]);
  assert.strictEqual(r.status, 0, `exit ${r.status}\nstdout:\n${r.stdout}\nstderr:\n${r.stderr}`);
  // Every check contributes one or more [PASS] lines; the four structural
  // checks (DM-2.1/2.2/2.3/2.4) and AC-T8-004 must each appear. AC-T8-006
  // emits one [PASS] per listed path (3 entries → 3 [PASS] lines).
  assert.ok(/\[PASS\] DM-2\.1/.test(r.stdout), 'DM-2.1 [PASS] missing');
  assert.ok(/\[PASS\] DM-2\.2/.test(r.stdout), 'DM-2.2 [PASS] missing');
  assert.ok(/\[PASS\] DM-2\.3/.test(r.stdout), 'DM-2.3 [PASS] missing');
  assert.ok(/\[PASS\] DM-2\.4/.test(r.stdout), 'DM-2.4 [PASS] missing');
  assert.ok(/\[PASS\] AC-T8-006/.test(r.stdout), 'AC-T8-006 [PASS] missing');
  assert.ok(/\[PASS\] AC-T8-004/.test(r.stdout), 'AC-T8-004 [PASS] missing');
  assert.ok(/0 failed/.test(r.stdout), `summary should report 0 failed:\n${r.stdout}`);
  fs.rmSync(dir, { recursive: true, force: true });
});

check('AC-T8-001: every [PASS] line and final summary appears on stdout', () => {
  const dir = makeProjectDir('ac001-shape', goodAgentsMd());
  materializeGoodArtifacts(dir);
  const r = runValidator([path.join(dir, 'AGENTS.md')]);
  assert.strictEqual(r.status, 0, `exit ${r.status}\nstderr:\n${r.stderr}`);
  // Summary line shape — used by CI / operators to confirm the verdict.
  assert.ok(/^Summary: \d+ passed, 0 failed \(\d+ total\)$/m.test(r.stdout),
    `summary line shape wrong:\n${r.stdout}`);
  // All [PASS] lines go to stdout (not stderr).
  assert.ok(!/\[PASS\]/.test(r.stderr), `[PASS] leaked to stderr:\n${r.stderr}`);
  fs.rmSync(dir, { recursive: true, force: true });
});

check('AC-T8-001: validator passes on real generator output (regression)', () => {
  // Generate a real AGENTS.md from the init-project generator against the
  // node-npm fixture and validate it. This proves the validator agrees with
  // the generator on every section the generator actually emits.
  const initScript = path.join(
    REPO_ROOT,
    '.opencode/skills/project-initialization/scripts/init_project_docs.sh'
  );
  const fixtureSrc = path.join(REPO_ROOT, 'tests', 'fixtures', 'repo-node-npm');
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'validate-amd-real-'));
  // Copy fixture into tmp (excluding .git which can't be tracked nested).
  for (const entry of fs.readdirSync(fixtureSrc, { withFileTypes: true })) {
    fs.cpSync(path.join(fixtureSrc, entry.name), path.join(tmp, entry.name), {
      recursive: true,
    });
  }
  fs.mkdirSync(path.join(tmp, '.git'), { recursive: true });
  const initRes = execFileSync(
    'bash',
    [
      initScript,
      '--noninteractive',
      '--project-dir', tmp,
      '--worktree-root', path.join(tmp, 'wt'),
      '--name', 'demo-node-app',
      '--github-owner', 'TestOrg',
      '--github-project-number', '1',
      '--description', 'Demo Node app',
      '--repo-role', 'service',
    ],
    { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 30000 }
  );
  // Sanity: the init script must have written AGENTS.md.
  assert.ok(fs.existsSync(path.join(tmp, 'AGENTS.md')),
    `init did not produce AGENTS.md\nstdout:\n${initRes}`);
  // All artifacts the generator lists in LCF should be present on disk after
  // a real init — so the validator should pass.
  const r = runValidator([path.join(tmp, 'AGENTS.md')]);
  assert.strictEqual(r.status, 0,
    `validator should pass on real generator output\nstdout:\n${r.stdout}\nstderr:\n${r.stderr}`);
  fs.rmSync(tmp, { recursive: true, force: true });
});

