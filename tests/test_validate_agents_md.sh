#!/usr/bin/env bash
#
# tests/test_validate_agents_md.sh — SPEC-001-T8 unit tests.
#
# Migrated from tests/test_validate_agents_md.js (SPEC-004-T4, issue #54).
# Assertion parity: all 34 Node checks migrated 1:1; none weakened.
#
# Drives `templates/scripts/validate-agents-md.sh` (a pure bash script) against
# crafted AGENTS.md inputs and asserts the DM-2 / AC-T8 contract from issue #9
# + ARCH-003 + SPEC-001 TEST-4:
#
#   - AC-T8-001: known-good AGENTS.md exits 0 with all checks passing.
#   - AC-T8-002: missing generation timestamp on line 1 → [FAIL] + exit 1.
#   - AC-T8-003: empty H2 section → [FAIL] + exit 1.
#   - AC-T8-004: placeholder text → [FAIL] + exit 1.
#   - AC-T8-005: missing '## Local Configuration Files' → [FAIL] + exit 1.
#   - AC-T8-006: path listed in LCF that does not exist → [FAIL] + exit 1;
#                directory entries (trailing /) are accepted as well as files.
#   - DM-2.2:    H1 and H3+ headings → [FAIL] + exit 1.
#   - DM-2.2/DM-2.3 "valid hand-edits" guardrail: reordered sections and
#                operator-tweaked generation comment do NOT trigger failures.
#   - Usage:     missing arg / --help / nonexistent file → exit 2.
#
# Run directly: `bash tests/test_validate_agents_md.sh`.
#
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/lib/init_helpers.sh"

VALIDATOR="$INIT_REPO_ROOT/templates/scripts/validate-agents-md.sh"
NODE_FIXTURE="$INIT_REPO_ROOT/tests/fixtures/repo-node-npm"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

OUT="$TMP/out.txt"
ERR="$TMP/err.txt"

# Canonical known-good generation comment (format the generator emits per
# DM-2.1 / AC-SPEC-012; the validator accepts any well-shaped header).
GOOD_HEADER='<!-- Generated by init-project v0.3.0 on 2026-07-21T05:29:36.616Z — edit freely -->'

# run_validator ARGS... — run the validator from the repo root; the validator
# resolves repo-root from the AGENTS.md argument's parent dir, so CWD does not
# matter for the assertions.
run_validator() {
  init_run_cmd "$OUT" "$ERR" "$INIT_REPO_ROOT" -- bash "$VALIDATOR" "$@"
}

# make_project_dir NAME CONTENT — write CONTENT to <dir>/AGENTS.md and echo
# the dir (validator resolves paths relative to that parent dir).
make_project_dir() {
  local name="$1" content="$2"
  local dir="$TMP/$name"
  mkdir -p "$dir"
  printf '%s\n' "$content" > "$dir/AGENTS.md"
  printf '%s' "$dir"
}

# good_agents_md [EXTRA_LINES...] — canonical known-good document.
good_agents_md() {
  cat <<EOF
$GOOD_HEADER

## Repository Identity

Demo project
Role: service

## Stack

Language: Node.js

## Local Configuration Files

- \`AGENTS.md\` — canonical agent guidance for this repository
- \`.github-project.env\` — ANT_TEAM_* runtime exports (sole project config source)
- \`.opencode/skills/do-task/\` — task worktree management scripts
$*
EOF
}

# materialize_good_artifacts DIR — create the files the known-good fixture
# claims exist (AC-T8-006 happy path).
materialize_good_artifacts() {
  local dir="$1"
  printf "export ANT_TEAM_GITHUB_OWNER='o'\n" > "$dir/.github-project.env"
  mkdir -p "$dir/.opencode/skills/do-task"
}

# --- AC-T8-001: known-good AGENTS.md passes ------------------------------------

init_suite "AC-T8-001 known-good passes"

dir="$(make_project_dir ac001 "$(good_agents_md)")"
materialize_good_artifacts "$dir"
run_validator "$dir/AGENTS.md"
assert_exit_zero "AC-T8-001: known-good AGENTS.md exits 0" "$INIT_RC"
assert_out_contains "$OUT" '\[PASS\] DM-2\.1' "AC-T8-001: DM-2.1 [PASS] present"
assert_out_contains "$OUT" '\[PASS\] DM-2\.2' "AC-T8-001: DM-2.2 [PASS] present"
assert_out_contains "$OUT" '\[PASS\] DM-2\.3' "AC-T8-001: DM-2.3 [PASS] present"
assert_out_contains "$OUT" '\[PASS\] DM-2\.4' "AC-T8-001: DM-2.4 [PASS] present"
assert_out_contains "$OUT" '\[PASS\] AC-T8-006' "AC-T8-001: AC-T8-006 [PASS] present"
assert_out_contains "$OUT" '\[PASS\] AC-T8-004' "AC-T8-001: AC-T8-004 [PASS] present"
assert_out_contains "$OUT" '0 failed' "AC-T8-001: summary reports 0 failed"

dir="$(make_project_dir ac001-shape "$(good_agents_md)")"
materialize_good_artifacts "$dir"
run_validator "$dir/AGENTS.md"
assert_exit_zero "AC-T8-001 (shape): known-good exits 0" "$INIT_RC"
assert_out_contains "$OUT" '^Summary: [0-9]+ passed, 0 failed \([0-9]+ total\)$' \
  "AC-T8-001: summary line shape"
if grep -qF '[PASS]' "$ERR"; then
  check FAIL "AC-T8-001: [PASS] leaked to stderr"
else
  check OK "AC-T8-001: no [PASS] on stderr"
fi

# Real generator output regression: init the node-npm fixture, then validate.
init_suite "AC-T8-001 real generator output (regression)"

real_dir="$TMP/validate-real"
cp -R "$NODE_FIXTURE/." "$real_dir/" 2>/dev/null || { mkdir -p "$real_dir"; cp -R "$NODE_FIXTURE/." "$real_dir/"; }
mkdir -p "$real_dir/.git"
init_run "$OUT" "$ERR" -- \
  --noninteractive --project-dir "$real_dir" --worktree-root "$real_dir/wt" \
  --name demo-node-app --github-owner TestOrg --github-project-number 1 \
  --description "Demo Node app" --repo-role service
assert_exit_zero "AC-T8-001 (real): init exits 0" "$INIT_RC"
assert_exists "AC-T8-001 (real): init produced AGENTS.md" "$real_dir/AGENTS.md"
run_validator "$real_dir/AGENTS.md"
assert_exit_zero "AC-T8-001 (real): validator passes on real generator output" "$INIT_RC"

# --- AC-T8-002: missing generation timestamp on line 1 --------------------------

init_suite "AC-T8-002 missing generation timestamp"

