  run_validator "$dir/AGENTS.md"
  assert_exit_nonzero "AC-T8-004 ($phrase): exits non-zero" "$INIT_RC"
  assert_out_contains "$ERR" '\[FAIL\] AC-T8-004' "AC-T8-004 ($phrase): [FAIL] on stderr"
  assert_out_contains "$ERR" 'AGENTS\.md:[0-9]+' "AC-T8-004 ($phrase): reports file:line"
