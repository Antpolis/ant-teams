assert_out_contains "$ERR" '\[FAIL\] DM-2\.1' "AC-T8-002 (comment): [FAIL] DM-2.1"

dir="$(make_project_dir ac002-noon '<!-- Generated by init-project v0.3.0 -->

## Local Configuration Files

- `AGENTS.md` — desc
')"
run_validator "$dir/AGENTS.md"
assert_exit_nonzero "AC-T8-002 (no ' on '): exits non-zero" "$INIT_RC"
assert_out_contains "$ERR" '\[FAIL\] DM-2\.1' "AC-T8-002 (no ' on '): [FAIL] DM-2.1"

dir="$(make_project_dir ac002-edit '<!-- Generated by init-project v9.9.9-custom on 2030-01-01T00:00:00Z by operator -->

## Local Configuration Files

- `AGENTS.md` — desc
')"
