if grep -qF '[FAIL] DM-2.1' "$ERR"; then
  check FAIL "AC-T8-002 (hand-edited): DM-2.1 should not flag well-shaped hand-edited header"
else
  check OK "AC-T8-002 (hand-edited): well-shaped hand-edited header not flagged"
